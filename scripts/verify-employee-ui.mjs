import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { mkdir } from "node:fs/promises";
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1490, height: 1054 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const go = async tab => {
  if (page.viewportSize().width < 900) await page.locator(".mobile-menu").click();
  await page.locator(`[data-destination="${tab}"]`).last().click();
};
try {
  await mkdir(".courio-review", { recursive: true });
  await page.goto("http://127.0.0.1:5173");
  await page.locator('[data-login-account="employee-marcus"]').click();
  await page.locator(".auth-overlay").waitFor({ state: "hidden" });
  assert(await page.locator("#dashboard.active .employee-today-tasks").isVisible());
  await page.screenshot({ path: ".courio-review/employee-today.png", fullPage: true });
  await go("team");
  assert(await page.locator(".team-row").count() > 0);
  await page.locator("[data-team-search]").fill("no-such-person");
  assert(await page.locator("[data-team-empty]").isVisible());
  await page.locator("[data-team-search]").fill("");
  await page.locator("[data-compose-colleague]").first().click();
  assert(await page.locator('[data-compose-field="to"]').inputValue());
  await go("tasks");
  await page.locator('#tasks [data-queue-filter="status"]').selectOption("Done");
  await page.locator('#tasks [data-queue-filter="status"]').selectOption("all");
  await page.locator('#tasks [data-request-task-follow-up]').first().click();
  await page.locator('[data-colleague-follow-up] [name="title"]').fill("Colleague browser check");
  await page.locator('[data-colleague-follow-up] [name="assignedTo"]').selectOption("emp-1");
  await page.locator('[data-colleague-follow-up] [type="submit"]').click();
  await page.locator('[data-colleague-follow-up]').waitFor({ state: "hidden" });
  await go("preferences");
  await page.locator('[name="language"]').selectOption("fr");
  await page.locator("[data-save-preferences]").click();
  await page.locator('[data-save-preferences]:enabled').waitFor();
  assert.equal(await page.locator("html").getAttribute("lang"), "fr");
  await go("triage");
  await page.locator("#triage .queue-item").first().click();
  await page.locator(".workspace-rule-suggestions").waitFor();
  await page.screenshot({ path: ".courio-review/employee-inbox.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await go("team");
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: ".courio-review/employee-mobile.png", fullPage: true });
  await page.reload();
  await page.locator(".session-pill").waitFor();
  assert.equal(await page.locator("html").getAttribute("lang"), "fr");
  assert.deepEqual(errors, []);
  console.log("PASS: employee Today, directory, compose recipient, task filters, colleague follow-up, EN/FR persistence, automation display, mobile overflow, no runtime errors.");
} finally { await browser.close(); }
