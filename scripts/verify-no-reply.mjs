import assert from "node:assert/strict";
const storage = new Map();
globalThis.window = { localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) } };
let api = await import("../src/api/mockApi.js");
await api.setDemoSession("admin-owner");
const newsletter = (await api.listEmails()).find(email => email.suggestedDisposition === "information_only");
await assert.rejects(api.markEmailNoReplyNeeded(newsletter.id));
assert(!(await api.listTasks()).some(task => task.emailId === newsletter.id));
const email = (await api.listEmails()).find(item => item.urgency === "High");
await api.getEmailThread(email.id);
await api.updateEmailCategory(email.id, "Newsletter");
await assert.rejects(api.markEmailNoReplyNeeded(email.id), "Changing a category must not bypass the reply workflow");
await api.setDemoSession("employee-marcus");
await assert.rejects(api.markEmailNoReplyNeeded(newsletter.id), "Cannot act on someone else's email");
await api.setDemoSession("admin-owner");
assert((await api.getEmailThread(newsletter.id)).canMarkNoReply);
const finished = await api.markEmailNoReplyNeeded(newsletter.id);
assert.equal(finished.workflowState, "no_reply_needed");
assert.equal(finished.draftReadyForHumanSend, false);
assert.equal(finished.canGenerateDraft, false);
assert.equal((await api.generateMorningDigest()).readyForHumanSend, 0);
assert.equal((await api.listDrafts()).length, 0);
api = await import("../src/api/mockApi.js?no-reply-reload");
assert((await api.listEmails()).find(item => item.id === newsletter.id).noReplyNeeded);
await api.reopenNoReplyEmail(newsletter.id);
await assert.rejects(api.markEmailNoReplyNeeded(newsletter.id), "Reopening requires a fresh review");
await api.getEmailThread(newsletter.id);
const manual = await api.getOrCreateEmailTask(newsletter.id);
await api.updateTask(manual.id, { notes: "Keep this explicit work" });
await api.markEmailNoReplyNeeded(newsletter.id);
assert((await api.listTasks()).some(task => task.id === manual.id && task.notes === "Keep this explicit work" && task.status === "Open"));
await api.reopenNoReplyEmail(newsletter.id);
await api.getEmailThread(newsletter.id);
await api.generateDraftReply(newsletter.id);
await assert.rejects(api.markEmailNoReplyNeeded(newsletter.id), "Existing drafts must not be bypassed");
// Legacy auto-task cleanup must preserve user edits and drafts.
const key = "courio.mockState.v1";
const legacy = JSON.parse(storage.get(key));
legacy.drafts = [];
legacy.emails.find(item => item.id === newsletter.id).workflowState = "needs_review";
legacy.tasks = [{ id: `task-${newsletter.id}`, emailId: newsletter.id, assignedTo: "", status: "Open", notes: "", createdAt: "2026-01-01", updatedAt: "2026-01-01", history: [{ at: "2026-01-01", label: "Task created from local inbox item" }] }];
storage.set(key, JSON.stringify(legacy));
api = await import("../src/api/mockApi.js?legacy-auto-task");
assert(!(await api.listTasks()).some(task => task.emailId === newsletter.id));
legacy.tasks[0].notes = "User work";
storage.set(key, JSON.stringify(legacy));
api = await import("../src/api/mockApi.js?legacy-edited-task");
assert((await api.listTasks()).some(task => task.emailId === newsletter.id && task.notes === "User work"));
console.log("PASS: review gate, ownership, category bypass rejection, no-reply persistence, no sent/draft counts, reopen, existing-draft protection, manual tasks and legacy cleanup.");
