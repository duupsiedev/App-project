import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { mkdir } from "node:fs/promises";
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1490, height: 1054 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const openNewsletter = async () => {
  await page.locator('[data-destination="triage"]').click();
  await page.locator('#triage .queue-item').filter({ hasText: "Weekly partner newsletter" }).click();
  await page.locator('#triageDetail .inline-review').waitFor();
};
try {
  await mkdir(".courio-review", { recursive: true });
  await page.goto("http://127.0.0.1:5173");
  await page.locator('[data-login-account="admin-owner"]').click();
  await page.locator('.auth-overlay').waitFor({ state: "hidden" });
  await openNewsletter();
  assert(!(await page.locator('#triageDetail').innerText()).includes("Draft required"));
  await page.locator('[data-no-reply-email]').click();
  await page.locator('[data-confirm-cancel]').click();
  assert(await page.locator('[data-no-reply-email]').isVisible());
  await page.locator('[data-no-reply-email]').click();
  await page.locator('[data-confirm-primary]').click();
  await page.locator('[data-reopen-no-reply]').waitFor();
  assert.equal(await page.locator('#triageDetail [data-generate-draft]').count(), 0);
  assert((await page.locator('#triageDetail').innerText()).includes("Nothing was sent"));
  await page.screenshot({ path: ".courio-review/no-reply-desktop.png", fullPage: true });
  await page.reload();
  await page.locator('.session-pill').waitFor();
  await openNewsletter();
  await page.locator('[data-reopen-no-reply]').click();
  await page.locator('#triageDetail .inline-review').waitFor({ state: "hidden" });
  await page.locator('#triage .queue-item').filter({ hasText: "Weekly partner newsletter" }).click();
  await page.locator('[data-no-reply-email]').waitFor();
  await page.locator('[data-no-reply-email]').click();
  await page.locator('[data-confirm-primary]').click();
  await page.locator('[data-reopen-no-reply]').waitFor();
  await page.locator('[data-destination="preferences"]').click();
  await page.locator('[name="language"]').selectOption("fr");
  await page.locator('[data-save-preferences]').click();
  await page.locator('html[lang="fr"]').waitFor();
  await openNewsletter();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert((await page.locator('#triageDetail').innerText()).includes("Aucun envoi"));
  await page.screenshot({ path: ".courio-review/no-reply-mobile-fr.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: review-only action, confirmation/cancel, no draft shortcut, persistence, reopen, French and mobile overflow.");
} finally { await browser.close(); }
