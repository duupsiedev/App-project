import assert from "node:assert/strict";
const storage = new Map();
globalThis.window = { localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) } };
let api = await import("../src/api/mockApi.js");
await api.setDemoSession("admin-owner");
const emails = await api.listEmails();
const ownEmail = emails.find(email => email.assignedTo === "emp-2");
const otherEmail = emails.find(email => email.assignedTo !== "emp-2");
await api.getEmailThread(otherEmail.id);
await api.getEmailThread(ownEmail.id);
const otherDraft = await api.generateDraftReply(otherEmail.id);
const ownDraft = await api.generateDraftReply(ownEmail.id);
const adminCompose = await api.saveComposeDraft({ to: "demo@example.test", subject: "Admin private compose", body: "Private composed message", attachments: [] });
const shared = await api.createTask({ title: "Shared contract test", assignedTo: "emp-1", collaboratorIds: ["emp-2"], dueAt: "2020-01-01" });
const privateTask = await api.createTask({ title: "Private admin task", assignedTo: "emp-1" });
await api.setDemoSession("employee-marcus");
assert((await api.listTasks()).some(task => task.id === shared.id && task.overdue));
assert(!(await api.listTasks()).some(task => task.id === privateTask.id));
assert((await api.listDrafts()).some(draft => draft.id === ownDraft.id));
assert(!(await api.listDrafts()).some(draft => draft.id === otherDraft.id));
assert(!(await api.listComposeDrafts()).some(draft => draft.id === adminCompose.id));
await assert.rejects(api.saveComposeDraft({ ...adminCompose, body: "Forbidden edit" }));
await api.getDraftDetail(ownDraft.id);
await api.saveDraft(ownDraft.id, "Reviewed employee draft for manual approval.");
assert((await api.listDrafts()).find(draft => draft.id === ownDraft.id).awaitingApproval);
await assert.rejects(api.approveDraft(ownDraft.id));
await assert.rejects(api.getDraftDetail(otherDraft.id));
await assert.rejects(api.saveDraft(otherDraft.id, "Must not save"));
await assert.rejects(api.updateTask(shared.id, { collaboratorIds: [] }));
await api.updateTask(shared.id, { notes: "Collaborator note" });
const followUp = await api.requestTaskFollowUp(shared.id, { title: "Please check", assignedTo: "emp-1" });
await api.savePersonalPreferences({ language: "fr" });
assert.equal((await api.getPersonalPreferences()).language, "fr");
await assert.rejects(api.toggleRule("rule-1"));
await api.setDemoSession("admin-owner");
assert.notEqual((await api.getPersonalPreferences()).language, "fr");
assert((await api.listTasks()).some(task => task.id === followUp.id && task.parentTaskId === shared.id));
await api.toggleRule("rule-1");
await api.setDemoSession("employee-marcus");
assert(!(await api.listEmails()).flatMap(email => email.automationSuggestions).some(rule => rule.id === "rule-1"));
api = await import("../src/api/mockApi.js?employee-reload");
assert.equal((await api.getPersonalPreferences()).language, "fr");
assert((await api.listTasks()).some(task => task.id === shared.id && task.notes === "Collaborator note"));
console.log("PASS: scoped drafts, forbidden direct access, shared tasks, collaborator permissions, linked follow-up, personal language, workspace rules, persistence.");
